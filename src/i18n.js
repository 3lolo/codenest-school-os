// Trilingual UI text — Arabic (default), Italian, English — for the whole
// site: the public marketing pages AND every signed-in dashboard screen,
// for every role. Arabic is also the only right-to-left language here, so
// this module doubles as the place that decides `dir="rtl"` (see isRtl()
// and how app.js's applyLang()/initLang() use it, mirroring the existing
// light/dark theme pattern in the same file).
//
// Usage: call `t("some.key")` anywhere a view builds a string. Pass a
// second `vars` object for simple `{placeholder}` interpolation, e.g.
// `t("students.removedNotice", { name: "Maya Hassan" })` where the
// dictionary entry contains "...{name}...". A key that's missing from the
// active language falls back to English, then to the raw key itself, so a
// forgotten translation never renders as a blank string.

export const LANGS = ["ar", "it", "en"];
export const RTL_LANGS = ["ar"];
export const DEFAULT_LANG = "ar";

export const LANG_LABELS = {
  ar: "العربية",
  it: "Italiano",
  en: "English",
};

export function isRtl(lang) {
  return RTL_LANGS.includes(lang);
}

let currentLang = DEFAULT_LANG;

export function setLang(lang) {
  currentLang = LANGS.includes(lang) ? lang : DEFAULT_LANG;
}

export function getLang() {
  return currentLang;
}

